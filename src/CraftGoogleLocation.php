namespace apt\craftgooglelocation;

use apt\craftgooglelocation\services\Service as ServiceService;
use apt\craftgooglelocation\models\Settings;
use apt\craftgooglelocation\fields\Location as LocationField;

use Craft;
use craft\base\Plugin;
use craft\services\Plugins;
use craft\events\PluginEvent;
use craft\services\Fields;
use craft\events\RegisterComponentTypesEvent;

use yii\base\Event;

/**
 * Class CraftGoogleLocation
 *
 * @author    Thomas Sømoen
 * @package   CraftGoogleLocation
 * @since     1.0.0
 *
 * @property  ServiceService $service
 */
class CraftGoogleLocation extends Plugin
{
    // Static Properties
    // =========================================================================

    /**
     * @var CraftGoogleLocation
     */
    public static $plugin;

    // Public Properties
    // =========================================================================

    /**
     * @var string
     */
    public $schemaVersion = '1.0.1';

    // Public Methods
    // =========================================================================

    /**
     * @inheritdoc
     */
    public function init()
    {
        parent::init();
        self::$plugin = $this;

        Event::on(
            Fields::class,
            Fields::EVENT_REGISTER_FIELD_TYPES,
            function (RegisterComponentTypesEvent $event) {
                $event->types[] = LocationField::class;
            }
        );

        Event::on(
            Plugins::class,
            Plugins::EVENT_AFTER_INSTALL_PLUGIN,
            function (PluginEvent $event) {
                if ($event->plugin === $this) {
                }
            }
        );

        Craft::info(
            Craft::t(
                'craft-google-location',
                '{name} plugin loaded',
                ['name' => $this->name]
            ),
            __METHOD__
        );
    }

    // Protected Methods
    // =========================================================================

    /**
     * @inheritdoc
     */
    protected function createSettingsModel()
    {
        return new Settings();
    }

    /**
     * @inheritdoc
     */
    protected function settingsHtml(): string
    {
        return Craft::$app->view->renderTemplate(
            'craft-google-location/settings',
            [
                'settings' => $this->getSettings()
            ]
        );
    }
}
